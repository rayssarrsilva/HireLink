export const T = { pt, en };
export type Dict = typeof pt;

export function savedLang(): Lang {
  try {
    const v = localStorage.getItem('hirelinks.lang');
    if (v === 'pt' || v === 'en') return v;
  } catch {
    /* storage unavailable */
  }
  return navigator.language.toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

export function storeLang(l: Lang): void {
  try {
    localStorage.setItem('hirelinks.lang', l);
  } catch {
    /* storage unavailable */
  }
}
